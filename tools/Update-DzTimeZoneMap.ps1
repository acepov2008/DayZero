#Requires -Version 5.1
<#
.SYNOPSIS
    Rebuilds builder\linux\timezones.json: Windows time zone id -> IANA name (what Linux uses).
.DESCRIPTION
    The data comes from the Unicode CLDR project (common/supplemental/windowsZones.xml), the
    same table .NET and ICU use. Only the "001" (golden) zone of each Windows id is kept.
.EXAMPLE
    .\tools\Update-DzTimeZoneMap.ps1
#>
[CmdletBinding()]
param(
    [string]$Url = 'https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml',
    [string]$SourceFile
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
if ($SourceFile) { [xml]$xml = Get-Content -LiteralPath $SourceFile -Raw }
else { [xml]$xml = (Invoke-WebRequest -Uri $Url -UseBasicParsing).Content }
$map = [ordered]@{}
foreach ($z in @($xml.supplementalData.windowsZones.mapTimezones.mapZone | Where-Object { $_.territory -eq '001' } | Sort-Object other)) {
    $map[[string]$z.other] = [string]$z.type
}
$doc = [ordered]@{
    '_doc'   = 'Windows time zone id -> IANA time zone. Generated by tools/Update-DzTimeZoneMap.ps1 from Unicode CLDR windowsZones.xml (territory 001). Do not edit by hand.'
    'zones'  = $map
}
$out = Join-Path $repo 'builder\linux\timezones.json'
[System.IO.File]::WriteAllText($out, ($doc | ConvertTo-Json -Depth 4) + "`n", (New-Object System.Text.UTF8Encoding($false)))
Write-Output ("{0} zones written to {1}" -f $map.Count, $out)
